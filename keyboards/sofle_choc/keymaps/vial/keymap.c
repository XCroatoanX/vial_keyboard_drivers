// Modifier keys status
static void render_mod_status(void) {
    uint8_t mods = get_mods() | get_oneshot_mods();

    oled_write_P(PSTR("Mods: "), false);
    oled_write_P((mods & MOD_MASK_SHIFT) ? PSTR("SHF ") : PSTR("    "), false);
    oled_write_P((mods & MOD_MASK_CTRL)  ? PSTR("CTL ") : PSTR("    "), false);
    oled_write_P((mods & MOD_MASK_ALT)   ? PSTR("ALT ") : PSTR("    "), false);
    oled_write_P((mods & MOD_MASK_GUI)   ? PSTR("GUI") : PSTR("   "), false);
    oled_write_P(PSTR("\n"), false);
}

// WPM display
static void render_wpm(void) {
    oled_write_P(PSTR("WPM: "), false);
    oled_write(get_u8_str(get_current_wpm(), ' '), false);
    oled_write_P(PSTR("\n"), false);
}

// Rotation settings
oled_rotation_t oled_init_user(oled_rotation_t rotation) {
    if (!is_keyboard_master()) {
        return OLED_ROTATION_180;
    } else {
        return OLED_ROTATION_0;  // Different rotation for left
    }
    return rotation;
}

